"""Embed src/bake.cl into src/bake_cl.h as one C string.

The OpenCL kernel is compiled at runtime by the driver, so its *source* has to
reach the user's machine. Embedding it in the binary rather than shipping a
.cl beside it means there is no second file to lose, and no path to guess from
inside an installed Blender extension.

A script of its own so that build.sh and CMakeLists.txt run the same step.

    python3 embed_kernel.py src/bake.cl src/bake_cl.h
"""

import sys


def main(source, target):
    with open(source, "r", encoding="utf-8") as handle:
        text = handle.read()
    # "\n" line endings whatever the host writes, so the header is the same
    # bytes on every platform it is generated on.
    with open(target, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by build.sh from src/bake.cl -- do not edit.\n")
        out.write("#pragma once\n\nstatic const char* kBakeKernelSource =\n")
        for line in text.splitlines():
            out.write('    "%s\\n"\n' % line.replace("\\", "\\\\").replace('"', '\\"'))
        out.write("    ;\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
